#!/usr/bin/env node
// make-fonts-ink.mjs: generates runtime/fonts-ink.css (used by the ink-wash style; run it when developing the skill, not when making a video).
// LXGW WenKai rules are copied from runtime/fonts.css; the brush fonts come from Fontsource's per-character slices,
// rewritten to load in the order "local → jsDelivr → unpkg".
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const rt = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'runtime');
const out = path.join(rt, 'fonts-ink.css');
const FONTS = [
  // [package, version, weight, possible local names]
  ['ma-shan-zheng', '5.3.1', 400, ['Ma Shan Zheng', 'MaShanZheng-Regular']],
  ['zhi-mang-xing', '5.3.0', 400, ['Zhi Mang Xing', 'ZhiMangXing-Regular']],
  ['liu-jian-mao-cao', '5.3.0', 400, ['Liu Jian Mao Cao', 'LiuJianMaoCao-Regular']],
];
const lxgw = fs.readFileSync(path.join(rt, 'fonts.css'), 'utf8').split('\n').filter((l) => l.includes("font-family:'LXGW WenKai'"));
let css = `/* fonts-ink.css: font loading rules (not the font files themselves), generated by scripts/make-fonts-ink.mjs
 * Each font is tried in order: ① installed locally → ② jsDelivr → ③ unpkg mirror. Web fonts are sliced by character, so only the characters actually used are downloaded.
 * If none is available (not installed locally and no network), it falls back to the backup fonts listed in FONTS in ink.js and renders as usual.
 * LXGW WenKai (霞鹜文楷): lxgw-wenkai-webfont@1.7.0. Ma Shan Zheng (马善政楷书), Zhi Mang Xing (钟齐志莽行书), Liu Jian Mao Cao (刘建毛草):
 * via Fontsource. All SIL OFL 1.1.
 */
${lxgw.join('\n')}
`;
let n = lxgw.length;
for (const [pkg, ver, w, locals] of FONTS) {
  const src = await (await fetch(`https://cdn.jsdelivr.net/npm/@fontsource/${pkg}@${ver}/${w}.css`)).text();
  for (const m of src.matchAll(/@font-face\s*{([^}]*)}/g)) {
    const body = m[1];
    const fam = /font-family:\s*'([^']+)'/.exec(body)[1];
    const file = /url\(\.\/files\/([^)]+\.woff2)\)/.exec(body)[1];
    const range = /unicode-range:\s*([^;]+);/.exec(body);
    const l = locals.map((x) => `local('${x}')`).join(',');
    css += `@font-face{font-family:'${fam}';font-style:normal;font-weight:${w};font-display:block;src:${l},url('https://cdn.jsdelivr.net/npm/@fontsource/${pkg}@${ver}/files/${file}') format('woff2'),url('https://unpkg.com/@fontsource/${pkg}@${ver}/files/${file}') format('woff2');${range ? `unicode-range:${range[1]};` : ''}}\n`;
    n++;
  }
}
fs.writeFileSync(out, css);
console.log(`Generated ${out} (${n} rules)`);
