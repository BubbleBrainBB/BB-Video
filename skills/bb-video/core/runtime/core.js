// core.js: time-driven composition runtime, shared by every style (bb-video/core/runtime; projects get a copy in lib/)
// Contract: the frame is a pure function of time. window.renderFrame(t) draws the frame at t seconds,
// without relying on requestAnimationFrame / Date.now / unseeded Math.random.
// The renderer (scripts/render.mjs) calls it frame by frame to take screenshots; opening the page directly in a browser starts the preview player.
(function () {
  Error.stackTraceLimit = 40;
  const clamp = (x, a = 0, b = 1) => Math.min(b, Math.max(a, x));
  const lerp = (a, b, p) => a + (b - a) * p;

  const ease = {
    linear: (p) => p,
    in: (p) => p * p * p,
    out: (p) => 1 - Math.pow(1 - p, 3),
    outQuart: (p) => 1 - Math.pow(1 - p, 4),
    inOut: (p) => (p < 0.5 ? 4 * p * p * p : 1 - Math.pow(-2 * p + 2, 3) / 2),
    inOutSine: (p) => -(Math.cos(Math.PI * p) - 1) / 2,
    outBack: (p) => { const c1 = 1.70158, c3 = c1 + 1; return 1 + c3 * Math.pow(p - 1, 3) + c1 * Math.pow(p - 1, 2); },
    // Simulates handwriting: slightly slower at stroke start and end, steady in the middle
    pen: (p) => 0.25 * p + 0.75 * (0.5 - 0.5 * Math.cos(Math.PI * p)),
  };

  function hashStr(s) {
    let h = 2166136261 >>> 0;
    for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 16777619); }
    return h >>> 0;
  }
  // mulberry32: reproducible random numbers
  function rng(seed) {
    let a = (typeof seed === 'string' ? hashStr(seed) : seed) >>> 0;
    return () => {
      a |= 0; a = (a + 0x6d2b79f5) | 0;
      let t = Math.imul(a ^ (a >>> 15), 1 | a);
      t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
      return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    };
  }

  // 0→1 progress, interpolating t over [start, start+dur]
  function progress(t, start, dur, e = ease.out) {
    if (dur <= 0) return t >= start ? 1 : 0;
    return e(clamp((t - start) / dur));
  }

  // ---------- Timeline (from timeline.js generated by scripts/tts.py) ----------
  const PUNCT = /[\s，。、？！；：“”‘’（）《》「」【】—…·,.?!;:'"()\[\]\-]/g;
  const norm = (s) => s.replace(PUNCT, '').toLowerCase();

  function timeline(data) {
    data = data || { duration: 10, lines: [] };
    const byId = new Map(data.lines.map((l) => [l.id, l]));
    const T = (id) => {
      const l = byId.get(id);
      if (!l) throw new Error(`timeline: narration line id "${id}" not found (check script.json and re-run tts.py)`);
      return l;
    };
    // Locate a word/phrase within a narration line; returns [start time, end time]
    function locate(id, phrase, nth = 0) {
      const l = T(id);
      const target = norm(phrase);
      const words = l.words || [];
      if (words.length) {
        let concat = '';
        const owner = [];
        words.forEach((w, i) => { const n = norm(w.text); concat += n; for (let k = 0; k < n.length; k++) owner.push(i); });
        let idx = -1, from = 0;
        for (let k = 0; k <= nth; k++) { idx = concat.indexOf(target, from); if (idx < 0) break; from = idx + 1; }
        if (idx >= 0) {
          const a = words[owner[idx]], b = words[owner[idx + target.length - 1]];
          return [a.start, b.end];
        }
      }
      // Fallback: estimate from character position across the line's duration
      const full = norm(l.text);
      const i = full.indexOf(target);
      if (i < 0) {
        console.warn(`timeline: in "${id}", could not find "${phrase}"; using the line's start time instead`);
        return [l.start, l.end];
      }
      const d = l.end - l.start;
      return [l.start + (d * i) / full.length, l.start + (d * (i + target.length)) / full.length];
    }
    T.start = (id) => T(id).start;
    T.end = (id) => T(id).end;
    T.word = (id, phrase, nth) => locate(id, phrase, nth)[0];
    T.wordEnd = (id, phrase, nth) => locate(id, phrase, nth)[1];
    T.at = (id, frac) => lerp(T(id).start, T(id).end, frac);
    T.lines = data.lines;
    T.chapters = data.chapters || [];
    T.duration = data.duration;
    T.current = (t) => data.lines.find((l) => t >= l.start && t < l.end) || null;
    return T;
  }

  // ---------- Caption segments: split each narration line into caption-sized pieces timed to the words ----------
  // Width is measured as display width (a CJK character 1, a Latin letter / digit 0.55, a space 0.3); breaks fall after punctuation,
  // between words of the voiceover's word timing, never inside an English word or a number. Returns [{ text, start, end }].
  function captionSegments(T, max = 20) {
    const caps = [];
    for (const l of T.lines) {
      if (!l.text || l.silence) continue;
      const text = l.text, words = l.words || [];
      const CJK = /[⺀-鿿豈-﫿＀-￯]/, LAT = /[A-Za-z0-9'’\-%]/;
      const wOf = (i, j) => { let w = 0; for (let k = i; k < j; k++) { const c = text[k]; w += CJK.test(c) ? 1 : c === ' ' ? 0.3 : 0.55; } return w; };
      const wpos = [], allowed = new Array(text.length + 1).fill(false);
      let from = 0;
      for (const w of words) {
        const i = text.indexOf(w.text, from);
        if (i < 0) { wpos.push(null); continue; }
        wpos.push(i); allowed[i] = allowed[i + w.text.length] = true; from = i + w.text.length;
      }
      // English punctuation (. , : ; ! ?) only counts as a break when followed by whitespace or at the end of the line; between letters/digits (3.5, 1,000, 3:30) it is part of the word
      const AN = /[A-Za-z0-9]/;
      const inWord = (k) => LAT.test(text[k] || '') || (/[.,:;_\/]/.test(text[k] || '') && AN.test(text[k - 1] || '') && AN.test(text[k + 1] || ''));
      const isBreak = (k) => /[，。！？；：—…]/.test(text[k]) || (/[,.!?;:]/.test(text[k]) && !inWord(k) && (k + 1 >= text.length || /[\s，。！？；：”’)）]/.test(text[k + 1])));
      for (let i = 1; i < text.length; i++) {
        if (/[\s、]/.test(text[i - 1]) || isBreak(i - 1)) allowed[i] = true;
        if (!words.length && CJK.test(text[i - 1]) && CJK.test(text[i])) allowed[i] = true;
        if (inWord(i - 1) && inWord(i)) allowed[i] = false;
      }
      const ranges = [];
      for (let i = 0, st = 0; i < text.length; i++) if (isBreak(i) && !isBreak(i + 1)) { ranges.push([st, i + 1]); st = i + 1; } else if (i === text.length - 1) ranges.push([st, text.length]);
      if (!ranges.length) ranges.push([0, text.length]);
      const ends = (r) => { const k = text.slice(0, r[1]).replace(/\s+$/, '').length - 1; return /[。！？]/.test(text[k]) || (/[.!?]/.test(text[k]) && isBreak(k)); };
      const merged = [];
      for (const r of ranges) { const last = merged[merged.length - 1]; if (last && wOf(last[0], r[1]) <= max && !ends(last)) last[1] = r[1]; else merged.push([...r]); }
      for (let i = 0; i < merged.length; i++) {  // pieces under 30% of the limit would flash by: merge them into a neighbour
        const r = merged[i];
        if (merged.length < 2 || wOf(r[0], r[1]) >= max * 0.3) continue;
        const prev = merged[i - 1], next = merged[i + 1];
        if (prev && !ends(prev)) { prev[1] = r[1]; merged.splice(i--, 1); } else if (next && !ends(r)) { next[0] = r[0]; merged.splice(i--, 1); }
      }
      const split = merged.flatMap(([s0, e0]) => {
        const n = Math.ceil(wOf(s0, e0) / (max + 3));
        if (n <= 1) return [[s0, e0]];
        const target = wOf(s0, e0) / n, out = [];
        let st = s0;
        for (let k = 1; k < n; k++) {
          let bst = -1, bd = Infinity;
          for (let i = st + 1; i < e0; i++) { if (!allowed[i]) continue; const d = Math.abs(wOf(st, i) - target); if (d < bd) { bd = d; bst = i; } }
          if (bst < 0) break;
          while (bst < e0 - 1 && /[，。！？；：、,.;:!?…—”’）)]/.test(text[bst])) bst++;   // Punctuation inside a sentence stays with the previous screen (the next screen never starts with "；")
          out.push([st, bst]); st = bst;
        }
        out.push([st, e0]);
        return out;
      });
      const starts = split.map(([s0]) => { const k = wpos.findIndex((p) => p !== null && p >= s0); return k >= 0 ? words[k].start : lerp(l.start, l.end, s0 / Math.max(1, text.length)); });
      split.forEach(([s0, e0], i) => {
        const cap = text.slice(s0, e0).trim().replace(/^[，。、；：,;:]+/, '').replace(/[，。、；：,;:—…]+$/, '').replace(/[，、]/g, ' ');
        caps.push({ text: cap, start: i === 0 ? l.start : starts[i], end: i < split.length - 1 ? starts[i + 1] : l.end + 0.25 });
      });
    }
    return caps;
  }

  // ---------- Composition entry point ----------
  // EV.composition({ build: async ({T}) => scene, width, height, fps, duration, audio })
  // scene must have render(t). build runs after fonts have loaded, so measuring text size is safe.
  function composition(opts) {
    // Aspect: when the page URL has ?aspect=9:16 (render.mjs --aspect 9:16) it is 1080×1920, 1:1 is 1080×1080; explicit width / height win.
    //   Boards (whiteboard / riso / ink) take their default size from this (EV.W / EV.H); write screen coordinates for both with EV.L(landscape value, portrait value)
    const asp = (typeof location !== 'undefined' && new URLSearchParams(location.search).get('aspect')) || opts.aspect || '16:9';
    const [dw, dh] = asp === '9:16' ? [1080, 1920] : asp === '1:1' ? [1080, 1080] : [1920, 1080];
    const width = opts.width || dw, height = opts.height || dh, fps = opts.fps || 30;
    EV.W = width; EV.H = height; EV.portrait = height > width; EV.aspect = asp;
    const T = timeline(window.TIMELINE);
    const stage = document.getElementById('stage');
    stage.style.width = width + 'px';
    stage.style.height = height + 'px';
    let scene = null;

    window.__composition = { width, height, fps, duration: opts.duration || T.duration };
    // With image / video media, returns a Promise that resolves once the images used by this frame are decoded (the renderer waits on it before taking the screenshot)
    // A scene may return a Promise from render(t) (canvas styles redraw once their images have decoded); otherwise wait for pending media
    window.renderFrame = (t) => { const r = scene ? scene.render(t) : null; if (r && r.then) return r; return EV.waitMedia ? EV.waitMedia() : undefined; };
    window.__ready = (async () => {
      const loaded = () => [...document.fonts].filter((f) => f.status === 'loaded').length;
      const before = loaded();
      scene = await opts.build({ T, stage, width, height, fps });
      if (scene && scene.ready) await scene.ready();   // e.g. stroke-order data the scene asked for while building
      // Web fonts download only the glyphs actually used: first load every character used by the whole video at once;
      // if new fonts arrive in the meantime, rebuild the layout once so text widths are measured with the final fonts
      await settleFonts(stage.textContent + T.lines.map((l) => l.text || '').join(''));
      if (loaded() !== before) {
        stage.innerHTML = '';
        infoReset();   // the rebuild registers its scenes / information visuals again
        scene = await opts.build({ T, stage, width, height, fps });
        if (scene && scene.ready) await scene.ready();
      }
      window.__fontInfo = fontInfo();
      window.__composition.duration = opts.duration || scene.duration || T.duration;
      scene.render(0);
      return window.__composition;
    })();
    window.__lint = () => (scene && scene.lint ? scene.lint() : []);
    window.__snapshot = () => (scene && scene.snapshot ? scene.snapshot() : null);
    window.__captions = () => (scene && scene.caps ? scene.caps : []);
    // When each piece of text appears (the gap checks count new text as "something happening"); the promo engine replaces this with its own F.texts
    window.__textWins = () => (scene && scene.textWins ? scene.textWins() : []);
    window.__ready.catch((e) => showError(e));
    if (!window.__RENDER__) window.__ready.then(() => player(stage, opts.audio, window.__composition));
  }

  // Load the subsets of every declared font that these characters need; with no network or missing fonts, wait at most 12 seconds, then continue with fallback fonts
  async function settleFonts(text) {
    // Each weight of each font must be loaded separately (subsets are split by weight; loading only the regular weight leaves bold glyphs blank)
    const faces = [...new Set([...document.fonts].map((f) => `${f.style} ${f.weight} 40px "${f.family.replace(/^["']|["']$/g, '')}"`))];
    const all = Promise.all(faces.map((f) => document.fonts.load(f, text + '0123456789+-%.').catch(() => {})));
    await Promise.race([all.then(() => document.fonts.ready), new Promise((r) => setTimeout(r, 12000))]);
  }
  // Whether each declared font ended up available (local or web); when unavailable, the frame uses a fallback font
  function fontInfo() {
    const by = {};
    for (const f of document.fonts) {
      const k = f.family.replace(/^["']|["']$/g, '');
      if (/^KaTeX/.test(k)) continue;
      by[k] = by[k] || { family: k, ok: false, tried: false };
      if (f.status === 'loaded') by[k].ok = true;
      if (f.status !== 'unloaded') by[k].tried = true;
    }
    return Object.values(by).filter((x) => x.tried);
  }

  function showError(e) {
    console.error(e);
    const d = document.createElement('pre');
    d.style.cssText = 'position:fixed;left:0;top:0;right:0;background:#b00020;color:#fff;padding:16px;font:14px Menlo,monospace;z-index:99;white-space:pre-wrap';
    d.textContent = 'Composition error: ' + (e && e.stack || e);
    document.body.appendChild(d);
  }

  // ---------- Preview player (only appears when opened directly in a browser) ----------
  function player(stage, audioSrc, comp) {
    document.body.classList.add('ev-preview');
    const bar = document.createElement('div');
    bar.className = 'ev-bar';
    bar.innerHTML = `<button data-k="play">Play</button><input type="range" min="0" step="0.01"><span class="ev-time"></span><span class="ev-hint">Space play/pause · ←/→ ±1s · ,/. step frame</span>`;
    document.body.appendChild(bar);
    const btn = bar.querySelector('button'), range = bar.querySelector('input'), label = bar.querySelector('.ev-time');
    const issues = window.__lint();
    if (issues.length) {
      const errs = issues.filter((i) => i.level === 'error').length;
      const badge = document.createElement('span');
      badge.className = 'ev-issues';
      badge.textContent = `Lint check: ${errs} error(s), ${issues.length - errs} warning(s) (click to jump to the first; details in the console)`;
      badge.style.cssText = `color:${errs ? '#ff6b6b' : '#f0b429'};cursor:pointer`;
      badge.onclick = () => seek(issues[0].t);
      bar.appendChild(badge);
      console.table(issues);
    }
    range.max = comp.duration;
    const audio = audioSrc ? new Audio(audioSrc) : null;
    let t = Number(new URLSearchParams(location.search).get('t')) || 0;
    let playing = false, wall0 = 0, t0 = 0;

    const fit = () => {
      const s = Math.min(window.innerWidth / comp.width, (window.innerHeight - 56) / comp.height);
      stage.style.transform = `scale(${s})`;
      stage.parentElement.style.height = comp.height * s + 'px';
      stage.parentElement.style.width = comp.width * s + 'px';
    };
    if (!stage.parentElement.classList.contains('ev-frame')) {
      const wrap = document.createElement('div');
      wrap.className = 'ev-frame';
      stage.parentElement.insertBefore(wrap, stage);
      wrap.appendChild(stage);
    }
    window.addEventListener('resize', fit); fit();

    const show = () => {
      window.renderFrame(t);
      range.value = t;
      label.textContent = `${t.toFixed(2)} / ${comp.duration.toFixed(2)} s`;
    };
    const play = () => {
      if (t >= comp.duration - 0.01) t = 0;
      playing = true; wall0 = performance.now(); t0 = t; btn.textContent = 'Pause';
      if (audio) { audio.currentTime = t; audio.play().catch(() => {}); }
      requestAnimationFrame(tick);
    };
    const pause = () => { playing = false; btn.textContent = 'Play'; if (audio) audio.pause(); };
    const seek = (x) => { t = clamp(x, 0, comp.duration); if (playing) { pause(); play(); } else show(); };
    function tick() {
      if (!playing) return;
      t = t0 + (performance.now() - wall0) / 1000;
      if (t >= comp.duration) { t = comp.duration; show(); pause(); return; }
      show();
      requestAnimationFrame(tick);
    }
    btn.onclick = () => (playing ? pause() : play());
    range.oninput = () => seek(Number(range.value));
    window.addEventListener('keydown', (e) => {
      if (e.code === 'Space') { e.preventDefault(); playing ? pause() : play(); }
      if (e.key === 'ArrowRight') seek(t + 1);
      if (e.key === 'ArrowLeft') seek(t - 1);
      if (e.key === '.') seek(t + 1 / comp.fps);
      if (e.key === ',') seek(t - 1 / comp.fps);
    });
    show();
  }

  // Beat grid: EV.beats(bpm, offset)(n) = the time of beat n (the same grid promo films use; works next to the narration timeline)
  const beats = (bpm = 120, offset = 0) => (n) => offset + (n * 60) / bpm;
  // Cast check (all styles with characters, see styles/CHARACTERS.md): any two different named characters must differ in at least
  // two visible attributes, or the audience can't tell who is who. flatten(spec) → { attribute: value } (default: one level of
  // nesting expanded, e.g. hair.colour). Warns once per cast object (console.warn shows up in render --check).
  const castSeen = new WeakSet();
  function castCheck(cast, flatten, style = '') {
    if (!cast || typeof cast !== 'object' || castSeen.has(cast)) return;
    castSeen.add(cast);
    const flat1 = (s) => { const o = {}; for (const [k, v] of Object.entries(s || {})) { if (v && typeof v === 'object' && !Array.isArray(v)) for (const [k2, v2] of Object.entries(v)) o[k + '.' + k2] = v2; else o[k] = v; } return o; };
    const names = Object.keys(cast), flat = names.map((n) => (flatten || flat1)(cast[n] || {}));
    for (let i = 0; i < names.length; i++) for (let j = i + 1; j < names.length; j++) {
      const keys = new Set([...Object.keys(flat[i]), ...Object.keys(flat[j])]);
      let d = 0; for (const k of keys) if (JSON.stringify(flat[i][k]) !== JSON.stringify(flat[j][k])) d++;
      if (d < 2) console.warn(`cast${style ? ' (' + style + ')' : ''}: "${names[i]}" and "${names[j]}" differ in only ${d} attribute(s) — the audience can't tell them apart; make them differ in at least two (face / hair / beard / headwear / clothes colour / build), see styles/CHARACTERS.md`);
    }
  }
  // Intentional cuts (the final-video check doesn't report them as "sudden jumps"; motion blur doesn't cross hard cuts): board styles register page turns and transitions here. The promo engine has its own F.cut / F.transition, which override window.__cuts / __transitions below
  const CUTS = [], TRANS = [];
  const cut = (t) => { if (!CUTS.some((c) => Math.abs(c - t) < 1e-3)) CUTS.push(t); };
  const transition = (a, b) => TRANS.push([a, b]);
  if (typeof window !== 'undefined') { window.__cuts ??= () => [...CUTS].sort((a, b) => a - b); window.__transitions ??= () => [...TRANS]; }
  // On-screen text (registered when board styles build their text components): the render check compares it with brief.md (fact check). Colour markup like {accent:…} is stripped; formulas ($…$, \commands) are not registered
  const FACTS = [];
  const fact = (str) => { if (typeof str !== 'string') return; const t = str.replace(/\{[a-zA-Z]+:([^{}]*)\}/g, '$1').replace(/<[^>]+>/g, '').trim(); if (!t || /\$|\\[a-zA-Z]/.test(t)) return; FACTS.push(t); if (typeof window !== 'undefined') window.__boardFacts = true; };
  if (typeof window !== 'undefined') window.__texts ??= () => [...new Set(FACTS)];
  // Information-density check (render --check): things on screen that "carry information" are registered here — flows, comparisons, charts, annotated screenshots, diagrams, boxes / arrows / circles / bars / shapes, real UI, drawings on the board.
  //   info(kind, a, b, o): on screen from a to b seconds; o.group = same group (the steps of one cue count as one point), o.visual: false = counts toward facts only, not as "has a visual" (lists)
  //   infoSource(fn): for per-element sources like boards, fn(t) returns the kinds of the information elements on screen (in the camera) at that moment
  //   scene(a, b, o): register a scene (o.role, o.end: true = end card); the check goes scene by scene, or line by line of narration when there is narration
  //   mute(fn): registrations made inside fn don't count (a cue already registered itself; its inner S.box / S.arrow aren't counted twice)
  const INFO = [], INFO_SRC = [], SCENES = [];
  let infoMute = 0;
  const info = (kind, a, b, o = {}) => { if (infoMute || !kind || !(a < 1e8)) return; INFO.push({ kind: String(kind), a: Math.round(a * 1000) / 1000, b: b === undefined || b === null || b > 1e8 ? 1e9 : Math.round(b * 1000) / 1000, group: o.group ?? null, visual: o.visual !== false }); };
  const infoSource = (fn) => INFO_SRC.push(fn);
  const scene = (a, b, o = {}) => SCENES.push({ a: Math.round(a * 1000) / 1000, b: Math.round(b * 1000) / 1000, role: o.role || '', end: !!o.end, name: o.name || '' });
  const infoReset = () => { INFO.length = 0; INFO_SRC.length = 0; SCENES.length = 0; };
  const mute = (fn) => { infoMute++; try { return fn(); } finally { infoMute--; } };
  const muted = () => infoMute > 0;   // Record board elements as they are built: ones drawn inside mute don't count as information
  if (typeof window !== 'undefined') {
    window.__info = () => INFO.map((x) => ({ ...x }));
    window.__infoAt = (ts) => ts.map((t) => [...new Set([...INFO.filter((x) => x.visual && t >= x.a && t < x.b).map((x) => x.kind), ...INFO_SRC.flatMap((f) => f(t) || [])])]);
    window.__scenes = () => SCENES.map((x) => ({ ...x }));
  }
  // One value each for landscape and portrait: EV.L(landscape value, portrait value) — without a portrait value the landscape one is used
  const L = (land, port) => (EV.portrait && port !== undefined ? port : land);
  // Ending overviews (whiteboard / riso / ink): with a voiceover, end with the narration instead of after it — seconds of music only after the voice are dead air.
  //   need = seconds the overview takes from its start until it is complete (zoom + numbering); drawn = when the last thing on the board is finished.
  //   If it would finish more than 0.5 s after the last line, start earlier: during the last line, never before that line starts, never before `drawn` + 0.3.
  //   late: true when even that ends well after the voice (the last thing was drawn as the voice ended) — the caller can then move faster.
  const fitEnding = (T, at, need, drawn = 0) => {
    const L = T && T.lines ? T.lines.filter((l) => !l.silence && l.end > l.start) : [], last = L[L.length - 1];
    if (!last || at >= 5e4) return { at, late: false };   // at ≥ 5e4: the exported board image, not the video
    const target = last.end + 0.5 - need;
    if (target >= at) return { at, late: false };
    const a = Math.max(target, drawn + 0.3, last.start);
    return { at: a, late: a > target + 0.3 };
  };
  window.EV = { clamp, lerp, ease, rng, hashStr, progress, timeline, composition, captionSegments, beats, castCheck, L, cut, transition, fact, info, infoSource, scene, mute, muted, fitEnding, W: 1920, H: 1080, portrait: false, aspect: '16:9' };
})();
